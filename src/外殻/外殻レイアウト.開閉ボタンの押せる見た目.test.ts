// 領域が利用できない文脈で、その領域の開閉ボタンが押せない見た目になり、押しても動かないことを検証する。
// 押せるのに何も起きないボタンは、その操作が成立していないのと同じである(エディター制作スキル第5条)。

import { describe, expect, it } from "vitest";
import { 外殻レイアウト } from "./外殻レイアウト";
import { 押せる状態 } from "./開閉ボタン";
import { パネルトグルボタン } from "./トグルボタン/パネルトグルボタン";
import { サイドバートグルボタン } from "./トグルボタン/サイドバートグルボタン";
import { トグルボタン as メニューのトグルボタンのクラス } from "../メニューバー/style.css";

function 基本オプション() {
    return { タイトル: "テストアプリ", アクティビティ項目一覧: [] };
}

// メニューバーの右ボタン群は パネル・サイドバー の順に並ぶ。
function メニューの開閉ボタンを引く(シェル: 外殻レイアウト): { パネル: Element; サイドバー: Element } {
    const 一覧 = シェル.dom.element.querySelectorAll(`.${メニューのトグルボタンのクラス}`);
    const パネル = 一覧[0];
    const サイドバー = 一覧[1];
    if (パネル === undefined || サイドバー === undefined) throw new Error("メニューバーの開閉ボタンが2つ見つからない");
    return { パネル, サイドバー };
}

function 押せるか(要素: Element): boolean {
    return 要素.getAttribute(押せる状態.attribute) === 押せる状態.value.押せる;
}

function クリックする(要素: Element): void {
    要素.dispatchEvent(new MouseEvent("click", { bubbles: true }));
}

describe("メニューバー内蔵の開閉ボタン", () => {
    it("下パネルが利用できない文脈では、パネルの開閉ボタンが押せない見た目になる", () => {
        const シェル = new 外殻レイアウト({ ...基本オプション(), パネル利用可能: false });
        expect(押せるか(メニューの開閉ボタンを引く(シェル).パネル)).toBe(false);
        // サイドバーは利用可能のままなので巻き添えで押せなくならない
        expect(押せるか(メニューの開閉ボタンを引く(シェル).サイドバー)).toBe(true);
    });

    it("押せない見た目のパネルの開閉ボタンは、押してもパネルが開かない", () => {
        const シェル = new 外殻レイアウト({ ...基本オプション(), パネル利用可能: false });
        クリックする(メニューの開閉ボタンを引く(シェル).パネル);
        expect(シェル.パネル表示中か()).toBe(false);
    });

    it("利用可能へ戻すと押せる見た目に戻り、押すとパネルが閉じる", () => {
        const シェル = new 外殻レイアウト({ ...基本オプション(), パネル利用可能: false });
        シェル.パネル利用可能を設定する(true);
        expect(押せるか(メニューの開閉ボタンを引く(シェル).パネル)).toBe(true);
        クリックする(メニューの開閉ボタンを引く(シェル).パネル);
        expect(シェル.パネル表示中か()).toBe(false);
    });

    it("右サイドバーが利用できない文脈では、サイドバーの開閉ボタンが押せない見た目になり押しても開かない", () => {
        const シェル = new 外殻レイアウト({ ...基本オプション(), 右サイドバー有効: true });
        expect(押せるか(メニューの開閉ボタンを引く(シェル).サイドバー)).toBe(true);

        シェル.サイドバー利用可能を設定する(false);
        expect(押せるか(メニューの開閉ボタンを引く(シェル).サイドバー)).toBe(false);
        クリックする(メニューの開閉ボタンを引く(シェル).サイドバー);

        シェル.サイドバー利用可能を設定する(true);
        // 押せない文脈でのクリックが人の表示希望を裏返していれば、戻したときに閉じてしまう
        expect(シェル.dom.element.querySelector('[class*="右サイドバー"]')?.hasAttribute("data-display")).toBe(false);
    });
});

describe("独立トグルボタンの預かり", () => {
    it("パネルの開閉ボタンを登録すると、利用できない文脈で押せない見た目になり押しても開かない", () => {
        const ボタン = new パネルトグルボタン();
        const シェル = new 外殻レイアウト({ ...基本オプション(), パネル利用可能: false, ステータスバー左: ボタン });
        ボタン.配線する(シェル);
        シェル.パネルの開閉ボタンを登録する(ボタン);

        expect(押せるか(ボタン.dom.element)).toBe(false);
        クリックする(ボタン.dom.element);
        expect(シェル.パネル表示中か()).toBe(false);

        シェル.パネル利用可能を設定する(true);
        expect(押せるか(ボタン.dom.element)).toBe(true);
        クリックする(ボタン.dom.element);
        expect(シェル.パネル表示中か()).toBe(false);
    });

    it("サイドバーの開閉ボタンを登録すると、利用できない文脈で押せない見た目になる", () => {
        const ボタン = new サイドバートグルボタン();
        const シェル = new 外殻レイアウト({ ...基本オプション(), ステータスバー左: ボタン });
        ボタン.配線する(シェル);
        シェル.サイドバーの開閉ボタンを登録する(ボタン);

        expect(押せるか(ボタン.dom.element)).toBe(true);
        シェル.サイドバー利用可能を設定する(false);
        expect(押せるか(ボタン.dom.element)).toBe(false);
    });
});
