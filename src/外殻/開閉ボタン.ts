// 領域（右サイドバー・下パネル・左サイドバー）の開閉ボタンが、その領域を「いま開けるか」を
// 見た目へ映すための口と状態定数。
//
// 領域には「開けてよい文脈か（利用可能）」という軸があり、利用不可のあいだ開閉ボタンを押しても
// 何も起きない。押せるのに何も起きないボタンは、その操作が成立していないのと同じであるため、
// 利用不可のあいだは押せない見た目にし、押しても動かないようにする。
// 参照: `~/.claude/skills/エディター制作` 第5条

export interface I開閉ボタン {
    押せるかを示す(押せるか: boolean): void;
}

// SengenUIガイド第13条のdata-attribute状態管理。押せない値のときの見た目は、
// 各ボタンのstyle.css.tsがglobalStyleで自分のクラスに限って定義する。
export const 押せる状態 = {
    attribute: "data-enabled",
    value: {
        押せる: "true",
        押せない: "false",
    },
} as const;
